-- 체크리스트 단계: 출국 준비 / 초기 정착 / 정착 이후
CREATE TABLE chk_step (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     varchar(50) NOT NULL,
    sort_ord integer NOT NULL,
    del_yn   char(1) NOT NULL DEFAULT 'N',
    del_dt   timestamptz,
    del_id   bigint,
    updt_id  bigint NOT NULL,
    updt_dt  timestamptz NOT NULL,
    crt_id   bigint NOT NULL,
    crt_dt   timestamptz NOT NULL
);

COMMENT ON TABLE chk_step IS '체크리스트 단계 (출국 준비 / 초기 정착 / 정착 이후)';
COMMENT ON COLUMN chk_step.id       IS '자동 생성되는 체크리스트 단계 ID';
COMMENT ON COLUMN chk_step.name     IS '단계명';
COMMENT ON COLUMN chk_step.sort_ord IS '단계 정렬 순서';
COMMENT ON COLUMN chk_step.del_yn   IS '삭제 여부 (기본값 N)';
COMMENT ON COLUMN chk_step.del_dt   IS '삭제 일시 (미삭제 시 NULL)';
COMMENT ON COLUMN chk_step.del_id   IS '삭제자 ID (미삭제 시 NULL)';
COMMENT ON COLUMN chk_step.updt_id  IS '수정자 ID';
COMMENT ON COLUMN chk_step.updt_dt  IS '수정 일시';
COMMENT ON COLUMN chk_step.crt_id   IS '생성자 ID';
COMMENT ON COLUMN chk_step.crt_dt   IS '생성 일시';